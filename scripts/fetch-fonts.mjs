// Fetch the webfonts we use and keep only the Latin subsets, saved locally so
// the app is fully offline-capable.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const FONT_DIR = path.join(ROOT, 'public', 'fonts')
const OUT_CSS = path.join(ROOT, 'src', 'fonts.css')

const cssUrl =
  'https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=Inter:wght@300..700&family=JetBrains+Mono:wght@400;500&display=swap'

const res = await fetch(cssUrl, {
  headers: {
    'user-agent':
      'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36',
  },
})
if (!res.ok) throw new Error(`font css ${res.status}`)
const css = await res.text()

fs.mkdirSync(FONT_DIR, { recursive: true })

const blocks = css.split('@font-face').slice(1)
const kept = []
const seen = new Map()

for (const block of blocks) {
  const isLatin = /unicode-range:[^;]*U\+0000-00FF/.test(block) && !/U\+0100-02BA/.test(block)
  if (!isLatin) continue
  const family = /font-family:\s*'([^']+)'/.exec(block)?.[1]
  const style = /font-style:\s*(\w+)/.exec(block)?.[1] || 'normal'
  const weight = /font-weight:\s*([\d\s]+);/.exec(block)?.[1]?.trim() || '400'
  const href = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1]
  if (!family || !href) continue
  const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${weight.replace(/\s+/g, '_')}.woff2`
  if (!seen.has(href)) {
    const bin = await fetch(href)
    if (!bin.ok) throw new Error(`font ${href} ${bin.status}`)
    fs.writeFileSync(path.join(FONT_DIR, file), Buffer.from(await bin.arrayBuffer()))
    seen.set(href, file)
  }
  const local = seen.get(href)
  kept.push(
    `@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url('/fonts/${local}') format('woff2');
  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}`,
  )
}

fs.writeFileSync(OUT_CSS, `/* generated by scripts/fetch-fonts.mjs */\n\n${kept.join('\n\n')}\n`)
console.log(`wrote ${kept.length} @font-face rules, ${seen.size} files to public/fonts`)
